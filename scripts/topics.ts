export function classifyTopic(q: Question): Topic {
  const manual = MANUAL[q.id];
  if (manual) return manual;

  const withOptions = [q.text, ...q.options].join('\n');
  for (const [pattern, topic, scope] of RULES[q.number] ?? []) {
    if (pattern.test(scope === 'with-options' ? withOptions : q.text)) return topic;
  }
  const byPosition = BY_POSITION[q.number];
  if (!byPosition) throw new Error(`${q.id}: нет темы по умолчанию для вопроса №${q.number}`);
  return byPosition;
}
