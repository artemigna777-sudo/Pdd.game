/**
 * Вопрос экзаменационного билета. Формат data/questions.json.
 * Тексты берутся из исходного файла без изменений по смыслу.
 */
export interface Question {
  /** Уникальный идентификатор, например "B12-Q07" (билет 12, вопрос 7). */
  id: string;
  /** Номер билета, с 1. */
  ticket: number;
  /** Номер вопроса в билете, с 1. */
  number: number;
  /** Текст вопроса. */
  text: string;
  /** Путь к картинке билета относительно public/, например "images/b12q07.jpg". Нет поля, если картинки нет. */
  image?: string;
  /** Варианты ответа в исходном порядке, без нумерации "1.", "2." из файла. */
  options: string[];
  /** Индекс правильного варианта в options, считая с нуля (в билете это вариант correct + 1). */
  correct: number;
  /** Пояснение из исходного файла. Нет поля, если в файле пояснения нет. */
  explanation?: string;
  /** Тема (раздел ПДД). */
  topic: string;
}
