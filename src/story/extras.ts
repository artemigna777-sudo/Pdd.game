/** Время Артёма в районе, секунд: по числу вопросов и точек главы и его темпу. */
export function rivalSeconds(rival: Rival, questions: number, points: number): number {
  return Math.round((questions * 22 + points * 15) * rival.pace);
}

/** Реакция Артёма на итог гонки (ничья по времени — разница меньше полминуты). */
export function raceReaction(faster: 'you' | 'artem' | 'tie', accurate: 'you' | 'artem' | 'tie'): Line {
  const key = `${faster}/${accurate}`;
  const lines: Record<string, string> = {
    'you/you': 'Ну ты даёшь! И быстрее, и точнее. Сдаюсь — до следующего района.',
    'you/tie': 'Точность одинаковая, но ты быстрее. В следующий раз не уступлю!',
    'you/artem': 'Ты быстрее, а я точнее! Считаем, ничья?',
    'tie/you': 'Приехали почти одновременно, но ошибок у тебя меньше. Ладно, ты точнее!',
    'tie/tie': 'Почти одновременно и одинаково точно. Ничья по всем статьям!',
    'tie/artem': 'Приехали почти одновременно, а я точнее! Кто бы мог подумать.',
    'artem/you': 'Я быстрее! …Но ошибок у меня больше. Виктор Петрович опять скажет, что это главное.',
    'artem/tie': 'Точность одинаковая, а я быстрее! Мопед — сила.',
    'artem/artem': 'Я и быстрее, и точнее! Но в следующем районе — реванш, да?',
  };
  return artem(lines[key]);
}

