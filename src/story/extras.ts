export interface SideStop {
  /** Подпись отметки на карте. */
  label: string;
  lines: Line[];
}

export interface SideQuest {
  giver: CharacterId;
  title: string;
  /** Просьба; последняя реплика — с выбором «Помогу!» / «Не сейчас». */
  offer: Line[];
  /** Сначала забрать, потом отвезти. */
  stops: [SideStop, SideStop];
}

