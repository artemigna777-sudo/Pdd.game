// ─── Гонка с Артёмом ──────────────────────────────────────────────────────────

export interface Rival {
  /** Что везёт Артём. */
  parcel: string;
  /** Во сколько раз Артём быстрее (<1) или медленнее (>1) среднего темпа. */
  pace: number;
  /** Доля верных ответов у Артёма, %. */
  accuracy: number;
  /** Вызов в начале главы (последняя реплика — с выбором). */
  challenge: Line[];
}

