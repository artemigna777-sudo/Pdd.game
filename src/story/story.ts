/** Подставить значения в текст реплик. */
export function fill(lines: readonly Line[], values: Record<string, string | number>): Line[] {
  return lines.map((l) => ({ ...l, text: l.text.replace(/\{(\w+)\}/g, (m, key: string) => (key in values ? String(values[key]) : m)) }));
}

/** Сколько пройденных точек нужно для сюжетной сцены главы (после трети и двух третей). */
export function beatThresholds(points: number): [number, number] {
  return [Math.max(1, Math.round(points / 3)), Math.max(2, Math.round((2 * points) / 3))];
}
