/**
 * Ещё рисунки «под гравюру»: конь, колесница, пламя. Нужны для ролика про Фаэтона (46).
 * Звери смотрят вправо, начало координат — на земле под серединой туловища.
 */
import { C } from './engine3.ts';
import { ink, sh, wh } from './etch.ts';
import { tube } from './etch2.ts';

const P = C.paper;
const I = C.ink;

type Pose = 'gallop' | 'rear' | 'stand';

/** Конь в профиль. `gallop` — летит, ноги вразброс; `rear` — встал на дыбы; `stand` — стоит. */
export function horse(x: number, y: number, s = 1, pose: Pose = 'gallop', pat = 'a120'): string {
  const legs: Record<Pose, string> = {
    gallop: `${tube('M-78,-112 L-132,-72 L-196,-34', 20, 'a90')}${tube('M-56,-108 L-92,-58 L-70,-8', 20, 'a90')}
      ${tube('M84,-116 L142,-84 L210,-44', 20, 'a90')}${tube('M70,-108 L104,-56 L88,-8', 20, 'a90')}
      ${ink('M-206,-40 l-24,6 l6,18 l26,-8 z')}${ink('M-78,-8 l-22,2 l4,16 l26,-2 z')}${ink('M212,-52 l22,10 l-8,16 l-22,-10 z')}${ink('M90,-8 l-4,18 l24,-2 l-2,-16 z')}`,
    rear: `${tube('M-70,-112 L-110,-60 L-112,-6', 20, 'a90')}${tube('M-46,-108 L-70,-56 L-52,-4', 20, 'a90')}
      ${tube('M90,-150 L164,-190 L226,-150', 20, 'a90')}${tube('M74,-142 L146,-166 L196,-120', 20, 'a90')}
      ${ink('M-120,-8 l-4,18 l26,-2 l-2,-16 z')}${ink('M-60,-6 l-4,18 l26,0 l-2,-16 z')}${ink('M226,-158 l14,12 l-16,10 l-8,-12 z')}${ink('M196,-128 l14,10 l-14,10 l-8,-12 z')}`,
    stand: `${tube('M-74,-112 L-80,-58 L-82,-6', 20, 'a90')}${tube('M-48,-108 L-46,-58 L-40,-6', 20, 'a90')}
      ${tube('M84,-112 L90,-58 L92,-6', 20, 'a90')}${tube('M62,-108 L66,-58 L66,-6', 20, 'a90')}
      ${ink('M-92,-8 l-4,18 l26,-2 l-2,-16 z')}${ink('M-50,-8 l-4,18 l26,0 l-2,-16 z')}${ink('M82,-8 l-4,18 l26,-2 l-2,-16 z')}${ink('M54,-8 l-4,18 l26,0 l-2,-16 z')}`,
  };
  const rot = pose === 'rear' ? ` rotate(-32 -20 -120)` : '';
  const tail = pose === 'gallop' ? 'M-108,-176 C-178,-186 -220,-150 -250,-96 C-200,-112 -160,-120 -104,-136 Z' : 'M-108,-176 C-160,-150 -180,-90 -168,-26 C-146,-80 -130,-116 -104,-136 Z';
  return `<g transform="translate(${x} ${y}) scale(${s})${rot}" stroke-width="3">
    ${sh(tail, 'b120')}
    ${legs[pose]}
    ${sh('M-114,-150 C-126,-212 -62,-234 0,-232 C70,-236 124,-218 138,-178 C144,-140 112,-108 70,-102 C20,-94 -62,-94 -104,-106 C-118,-114 -116,-132 -114,-150 Z', pat)}
    <path d="M-96,-132 C-60,-158 -20,-150 0,-120 M30,-196 C50,-170 40,-140 22,-122" stroke-width="2.5"/>
    ${sh('M92,-222 C120,-292 152,-334 190,-342 L220,-302 C190,-272 176,-220 154,-168 Z', pat)}
    ${wh('M184,-346 C220,-364 268,-332 298,-284 C306,-266 292,-254 278,-262 C256,-268 228,-270 214,-300 Z')}
    ${ink('M194,-346 l-6,-36 l24,28 z')}
    ${ink('M92,-226 C108,-300 150,-348 188,-356 C162,-326 138,-286 126,-222 Z')}
    <path d="M110,-250 q-14,-6 -22,6 M128,-290 q-14,-6 -22,6 M150,-322 q-14,-6 -22,6" stroke="${P}" stroke-width="2.5"/>
    <circle cx="234" cy="-322" r="5.5" fill="${I}"/><path d="M286,-270 q10,2 10,10 M270,-258 q-12,0 -18,-8" stroke-width="3"/>
  </g>`;
}

/** Пламя: языки, внутри светлее. */
export function flame(x: number, y: number, h: number): string {
  const k = h / 120;
  const d = `M${x - 34 * k},${y} C${x - 50 * k},${y - 50 * k} ${x - 12 * k},${y - 60 * k} ${x - 20 * k},${y - 110 * k} C${x + 8 * k},${y - 90 * k} ${x + 14 * k},${y - 60 * k} ${x + 8 * k},${y - 40 * k} C${x + 26 * k},${y - 60 * k} ${x + 30 * k},${y - 100 * k} ${x + 22 * k},${y - 130 * k} C${x + 60 * k},${y - 90 * k} ${x + 64 * k},${y - 30 * k} ${x + 34 * k},${y} Z`;
  const inner = `M${x - 14 * k},${y} C${x - 22 * k},${y - 30 * k} ${x - 2 * k},${y - 40 * k} ${x},${y - 66 * k} C${x + 22 * k},${y - 40 * k} ${x + 22 * k},${y - 16 * k} ${x + 14 * k},${y} Z`;
  return `${sh(d, 'b60', 'stroke-width="3"')}${wh(inner, 'stroke-width="2"')}`;
}

/** Колесо со спицами. */
export const wheel = (cx: number, cy: number, r: number, turn = 0) =>
  `<g transform="rotate(${turn} ${cx} ${cy})"><circle cx="${cx}" cy="${cy}" r="${r}" fill="${P}" stroke-width="5"/><circle cx="${cx}" cy="${cy}" r="${r * 0.86}" stroke-width="2.5"/>
   ${Array.from({ length: 8 }, (_, i) => {
     const a = (i * Math.PI) / 4;
     return `<path d="M${cx},${cy} L${(cx + Math.cos(a) * r).toFixed(1)},${(cy + Math.sin(a) * r).toFixed(1)}" stroke-width="5"/>`;
   }).join('')}
   <circle cx="${cx}" cy="${cy}" r="${r * 0.16}" fill="${I}"/></g>`;

